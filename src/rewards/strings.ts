export const strings = { ar, en };
export type Strings = typeof ar;
export type StringKey = { [K in keyof Strings]: Strings[K] extends string ? K : never }[keyof Strings];

export const fmt = (s: string, v: Record<string, string | number> = {}) =>
  s.replace(/\{(\w+)\}/g, (_, k: string) => (v[k] != null ? String(v[k]) : ''));
export const nf = (n: number | null | undefined) =>
  Number(n || 0).toLocaleString('en-US', { maximumFractionDigits: 2 });
export function fmtDate(d: string | null | undefined, lang: Lang, withTime = false): string {
  if (!d) return '';
  const x = new Date(d.length === 10 ? d + 'T12:00:00' : d);
  if (isNaN(x.getTime())) return d;
  const m = strings[lang].months[x.getMonth()];
  const day = `${x.getDate()} ${m}${withTime ? '' : ' ' + x.getFullYear()}`;
  if (!withTime) return day;
  return `${day} ${String(x.getHours()).padStart(2, '0')}:${String(x.getMinutes()).padStart(2, '0')}`;
}
/** Looks up a computed key such as 'tier_' + name, falling back to `fallback`. */
export const pick = (t: Strings, key: string, fallback = ''): string => {
  const v = (t as unknown as Record<string, unknown>)[key];
  return typeof v === 'string' ? v : fallback;
};
